-- Create Database
CREATE DATABASE WORKSHOP_DB;

-- Create Schema
CREATE SCHEMA WORKSHOP_DB.PUBLIC;

-- Use Database & Schema
USE DATABASE WORKSHOP_DB;
USE SCHEMA PUBLIC;

-- Create Table
CREATE OR REPLACE TABLE EMPLOYEE (
    EMP_ID INT,
    EMP_NAME STRING,
    DEPARTMENT STRING,
    SALARY NUMBER(10,2)
);

--Create the Stage
CREATE STAGE MY_STAGE;

-- Load CSV File
COPY INTO EMPLOYEE
FROM @MY_STAGE/employee.csv
FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1);

-- SQL Query
SELECT * FROM EMPLOYEE;

-- View
CREATE OR REPLACE VIEW VW_HIGH_SALARY AS
SELECT *
FROM EMPLOYEE
WHERE SALARY > 50000;

-- Analytics
SELECT DEPARTMENT,
       COUNT(*) AS EMP_COUNT,
       AVG(SALARY) AS AVG_SALARY
FROM EMPLOYEE
GROUP BY DEPARTMENT
ORDER BY AVG_SALARY DESC;
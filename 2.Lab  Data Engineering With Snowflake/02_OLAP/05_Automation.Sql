
-- Create a pipe to automatically load CSV files into staging table
 CREATE OR REPLACE PIPE RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_PIPE
AUTO_INGEST = TRUE
AS
COPY INTO RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE
FROM @RETAIL_DB.STAGING_SCHEMA.MY_STAGE
FILE_FORMAT = (FORMAT_NAME = RETAIL_DB.STAGING_SCHEMA.MY_CSV_FORMAT)
ON_ERROR = 'CONTINUE';



CREATE OR REPLACE PROCEDURE RETAIL_DB.RAW_SCHEMA.LOAD_DIM_FACT_SQL()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN

    -- 1. Insert into DIM_CUSTOMER
   INSERT INTO RETAIL_DB.RAW_SCHEMA.DIM_CUSTOMER (CustomerID, CustomerName, Phone, Email)
SELECT DISTINCT s.CustomerID, s.CustomerName, s.Phone, s.Email
FROM RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE s
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.RAW_SCHEMA.DIM_CUSTOMER c
    WHERE c.CustomerID = s.CustomerID
);

    -- 2. Insert into DIM_PRODUCT
    INSERT INTO RETAIL_DB.RAW_SCHEMA.DIM_PRODUCT (ProductID, ProductName, Category)
SELECT DISTINCT s.ProductID, s.ProductName, s.Category
FROM RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE s
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.RAW_SCHEMA.DIM_PRODUCT p
    WHERE p.ProductID = s.ProductID
);

    -- 3. Insert into DIM_DATE
   INSERT INTO RETAIL_DB.RAW_SCHEMA.DIM_DATE (DateKey, FullDate, DayOfWeek, Month, Quarter, Year)
SELECT DISTINCT 
    TO_NUMBER(TO_CHAR(TO_DATE(s.OrderDate,'YYYY-MM-DD'), 'YYYYMMDD')) AS DateKey,
    TO_DATE(s.OrderDate,'YYYY-MM-DD') AS FullDate,
    TO_CHAR(TO_DATE(s.OrderDate,'YYYY-MM-DD'), 'DY') AS DayOfWeek,
    TO_CHAR(TO_DATE(s.OrderDate,'YYYY-MM-DD'), 'Mon') AS Month,
    TO_CHAR(TO_DATE(s.OrderDate,'YYYY-MM-DD'), 'Q') AS Quarter,
    TO_NUMBER(TO_CHAR(TO_DATE(s.OrderDate,'YYYY-MM-DD'), 'YYYY')) AS Year
FROM RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE s
WHERE NOT EXISTS (
    SELECT 1
    FROM RETAIL_DB.RAW_SCHEMA.DIM_DATE d
    WHERE d.DateKey = TO_NUMBER(TO_CHAR(TO_DATE(s.OrderDate,'YYYY-MM-DD'),'YYYYMMDD'))
);

    -- 4. Insert into FACT_RETAIL_SALES
   INSERT INTO RETAIL_DB.RAW_SCHEMA.FACT_RETAIL_SALES
    (OrderID, CustomerKey, ProductKey, DateKey, Quantity, UnitPrice, LineAmount)
SELECT
    s.OrderID,
    c.CustomerKey,
    p.ProductKey,
    d.DateKey,
    TRY_TO_NUMBER(s.Quantity),
    TRY_TO_NUMBER(s.UnitPrice),
    TRY_TO_NUMBER(s.LineAmount)
FROM RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE s
JOIN RETAIL_DB.RAW_SCHEMA.DIM_CUSTOMER c ON s.CustomerID = c.CustomerID
JOIN RETAIL_DB.RAW_SCHEMA.DIM_PRODUCT  p ON s.ProductID = p.ProductID
JOIN RETAIL_DB.RAW_SCHEMA.DIM_DATE     d ON TO_DATE(s.OrderDate,'YYYY-MM-DD') = d.FullDate
    WHERE NOT EXISTS (
        SELECT 1 
        FROM RETAIL_DB.RAW_SCHEMA.FACT_RETAIL_SALES f
        WHERE f.OrderID = s.OrderID
    );

    RETURN 'DIM & FACT tables loaded successfully!';

END;
$$;



CREATE OR REPLACE TASK RETAIL_DB.RAW_SCHEMA.LOAD_FACT_TASK
  WAREHOUSE = RETAIL_WH
  SCHEDULE = 'USING CRON */2 * * * * UTC'  -- every 2 minutes
AS
  CALL RETAIL_DB.RAW_SCHEMA.LOAD_DIM_FACT_SQL();



ALTER TASK RETAIL_DB.RAW_SCHEMA.LOAD_FACT_TASK RESUME;
ALTER TASK RETAIL_DB.RAW_SCHEMA.LOAD_FACT_TASK suspend;


-- Check task status
SHOW TASKS LIKE 'LOAD_FACT_TASK' IN SCHEMA RETAIL_DB.RAW_SCHEMA;


-- 1.Create a compute warehouse
CREATE OR REPLACE WAREHOUSE RETAIL_WH
WITH
  WAREHOUSE_SIZE = 'XSMALL'   
  AUTO_SUSPEND = 300          
  AUTO_RESUME = TRUE          
  INITIALLY_SUSPENDED = TRUE  
  COMMENT = 'Warehouse for Retail data pipeline (staging, raw, presentation)';



-- 2. Create Database
CREATE OR REPLACE DATABASE RETAIL_DB;

-- 3. Create Schemas
CREATE OR REPLACE SCHEMA RETAIL_DB.STAGING_SCHEMA;
CREATE OR REPLACE SCHEMA RETAIL_DB.TRANSFORMATION_SCHEMA;
CREATE OR REPLACE SCHEMA RETAIL_DB.PRESENTATION_SCHEMA;

-- 3. Create Stage (for loading files)
CREATE OR REPLACE STAGE RETAIL_DB.STAGING_SCHEMA.my_stage;

-- 4. File Format (CSV)
CREATE OR REPLACE FILE FORMAT RETAIL_DB.STAGING_SCHEMA.my_csv_format
  TYPE = 'CSV'
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  SKIP_HEADER = 1
  NULL_IF = ('NULL', 'null')
  EMPTY_FIELD_AS_NULL = TRUE;



list @RETAIL_DB.STAGING_SCHEMA.MY_STAGE

select $1,$2
from @RETAIL_DB.STAGING_SCHEMA.MY_STAGE/retail_sales_export_20250906_191633.csv
(FILE_FORMAT => RETAIL_DB.STAGING_SCHEMA.my_csv_format);


CREATE OR REPLACE TABLE RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE (
    OrderID         STRING,
    OrderDate       STRING,   
    CustomerID      STRING,
    CustomerName    STRING,
    Phone           STRING,
    Email           STRING,
    ProductID       STRING,
    ProductName     STRING,
    Category        STRING,
    Quantity        STRING,
    UnitPrice       STRING,
    LineAmount      STRING
);


COPY INTO RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE
FROM @RETAIL_DB.STAGING_SCHEMA.my_stage
FILE_FORMAT = (FORMAT_NAME = RETAIL_DB.STAGING_SCHEMA.my_csv_format);

select * from RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE;


--Automation
CREATE OR REPLACE PIPE RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_PIPE
AUTO_INGEST = TRUE
AS
COPY INTO RETAIL_DB.STAGING_SCHEMA.RETAIL_SALES_STAGE
FROM @RETAIL_DB.STAGING_SCHEMA.MY_STAGE
FILE_FORMAT = (FORMAT_NAME = RETAIL_DB.STAGING_SCHEMA.MY_CSV_FORMAT)
ON_ERROR = 'CONTINUE';
